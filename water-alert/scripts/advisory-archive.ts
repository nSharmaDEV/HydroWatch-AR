// `npm run advisory:archive` — local only. Recovers ADH boil-water advisories
// issued before WAVE began collecting, from dated Internet Archive captures of
// ADH's own notice page. Writes:
//   src/imported-advisories-archive.ts            (generated records)
//   docs/research/adh-advisory-archive/log.json   (per-run evidence)
// Usage: npm run advisory:archive [-- --dry-run] [-- --limit=N]
// Never deploys, commits or notifies; review the diff before committing.
//
// These are historical documents, not live status: they cannot enter the source
// snapshot, polling or notification flows. Coverage is a sample bounded by when
// the Archive happened to capture the page.
import { mkdirSync, writeFileSync } from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import { adhSystemPlaceId } from '../server/parsers.js'
import { DIRECTORY } from '../src/water-system-directory.js'
import type { ImportedAdvisory } from '../src/imported-advisories.js'
import { advisoryId, advisoryKey, captureDate, captureTimestamps, captureUrl, captureViewUrl, mergeCaptures, parseCapture, type ArchivedAdvisory } from './advisory-archive-lib.js'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const archive = path.join(root, 'docs/research/adh-advisory-archive')
const args = process.argv.slice(2)
const dryRun = args.includes('--dry-run')
const limit = Number(args.find(a => a.startsWith('--limit='))?.slice('--limit='.length)) || 3000
const today = new Date().toLocaleDateString('en-CA', { timeZone: 'America/Chicago' })

const timestamps = await captureTimestamps(fetch, limit)
console.log(`${timestamps.length} archived capture(s) of the ADH notice page.`)

const found = new Map<string, ArchivedAdvisory>()
const log: { capture: string; rows: number; status: 'ok' | 'failed' }[] = []
let failed = 0
// Sequential and unhurried: this is a free public archive, not a feed.
for (const timestamp of timestamps) {
  try {
    const response = await fetch(captureUrl(timestamp), { signal: AbortSignal.timeout(60_000), headers: { 'User-Agent': 'WAVE-advisory-archive' } })
    if (!response.ok) throw new Error(`HTTP ${response.status}`)
    const rows = parseCapture(await response.text())
    if (!rows.length) throw new Error('no notice rows')
    for (const row of rows) found.set(advisoryKey(row), mergeCaptures(found.get(advisoryKey(row)), row, timestamp))
    log.push({ capture: timestamp, rows: rows.length, status: 'ok' })
  } catch (error) {
    // A failed capture is a gap in coverage, never evidence of no advisory.
    failed++
    log.push({ capture: timestamp, rows: 0, status: 'failed' })
    console.warn(`  capture ${timestamp} skipped: ${(error as Error).message}`)
  }
}

// Exact published name only, the same rule the live parser uses. A system the
// EPA directory does not list keeps its advisory out rather than guessing.
const directory = new Map(DIRECTORY.systems.map(s => [s.placeId, s]))
const records: ImportedAdvisory[] = []
let unmatched = 0
for (const row of found.values()) {
  const placeId = adhSystemPlaceId(row.system)
  const system = directory.get(placeId)
  if (!system) { unmatched++; continue }
  records.push({
    id: advisoryId(system.pwsid, row),
    placeId,
    publisher: 'Arkansas Department of Health',
    issued: row.issued,
    lifted: row.lifted,
    area: row.area,
    reason: row.reason,
    noticeUrl: captureViewUrl(row.capture),
    capturedOn: captureDate(row.capture),
    reviewedOn: today,
    identityUrl: `https://health.arkansas.gov/Eng/WS.aspx?ID=${system.pwsid.replace(/^AR0*/, '').padStart(3, '0')}`,
    observedNoticeIds: [],
  })
}
records.sort((a, b) => a.id.localeCompare(b.id))

const suppliers = new Set(records.map(r => r.placeId)).size
console.log(`${log.filter(l => l.status === 'ok').length} capture(s) read, ${failed} failed.`)
console.log(`${records.length} advisory record(s) across ${suppliers} supplier(s); ${unmatched} not in the EPA directory and left out.`)

if (dryRun) { console.log('Dry run: nothing written.'); process.exit(0) }

const module = `// GENERATED by \`npm run advisory:archive\` (scripts/advisory-archive.ts).
// Do not hand-edit: hand-reviewed records belong in imported-advisories.ts.
// Recovered from dated Internet Archive captures of ADH's own boil-water page.
// A sample, never a complete record: advisories issued and lifted between two
// captures were never on a captured page. Run log: docs/research/adh-advisory-archive/.
import type { ImportedAdvisory } from './imported-advisories'

export const ARCHIVED_ADVISORIES: readonly ImportedAdvisory[] = ${JSON.stringify(records, null, 2)}
`
writeFileSync(path.join(root, 'src/imported-advisories-archive.ts'), module)
mkdirSync(archive, { recursive: true })
writeFileSync(path.join(archive, 'log.json'), `${JSON.stringify({ runOn: today, captures: log, advisories: records.length, suppliers, unmatched }, null, 2)}\n`)
console.log('Wrote src/imported-advisories-archive.ts and the run log. Review the diff; nothing was committed or deployed.')
