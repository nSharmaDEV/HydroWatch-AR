import { test, expect } from '@playwright/test'
import { helpGuideStrings } from '../../src/help-guide-strings'

test.use({ reducedMotion: 'reduce' })
for (const language of ['en', 'es'] as const) test(`detected report and action questions automatically reach the editable email (${language})`, async ({ page, context, baseURL }, info) => {
  test.setTimeout(60_000)
  const es = language === 'es', place = { id: `ADH:${'a'.repeat(64)}`, name: 'Synthetic supplier', county: 'Benton', kind: 'system' }
  const title = es ? 'Faltan muestras bacteriológicas' : 'Missing bacteriological samples'
  const at = new Date().toISOString(), errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  await context.addInitScript(({ language, place }) => {
    sessionStorage.setItem('wave:logo-intro:v1', 'seen')
    if (!localStorage.getItem('water-alert:live:v1')) localStorage.setItem('water-alert:live:v1', JSON.stringify({ watches: [place.id], liftWatches: [], language, checkOnOpen: true }))
    localStorage.setItem('wave:report-check:v1', JSON.stringify({ [place.id]: { state: 'aiSummarized', year: 2025, url: 'https://health.arkansas.gov/eng/d.aspx?P=001&YEAR=2025', checkedAt: '2026-11-17', summarizedOn: '2026-11-17', model: 'synthetic', issues: [{ category: 'monitoring', title: { en: 'Missing bacteriological samples', es: 'Faltan muestras bacteriológicas' }, heading: { en: 'Monitoring', es: 'Monitoreo' }, action: { en: 'None listed', es: 'Ninguna indicada' }, page: 2, reportedFrom: '10/01/2025', reportedThrough: '10/31/2025' }] } }))
  }, { language, place })
  await context.route('**/*', route => {
    const url = new URL(route.request().url())
    if (url.origin !== baseURL) return route.abort()
    if (url.pathname === '/api/status') return route.fulfill({ json: { places: [place], sources: ['ADH', 'ADEQ'].map(agency => ({ agency, records: [], lastSuccessAt: at, retrievedAt: at, error: null })), archive: [], coverageStart: at } })
    if (url.pathname === '/api/help/session') return route.fulfill({ json: { enabled: false, user: null, delivery: false, accountUrl: null } })
    if (url.pathname === '/api/push/config') return route.fulfill({ json: { enabled: false } })
    if (url.pathname.startsWith('/api/')) return route.abort()
    return route.continue()
  })
  const capture = async (name: string) => {
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
    if (process.env.WAVE_HELP_CAPTURE_DIR) await page.screenshot({ path: `${process.env.WAVE_HELP_CAPTURE_DIR}/${info.project.name}-${language}-${name}.png`, fullPage: true })
  }
  await page.goto('/')
  await page.getByRole('button', { name: es ? 'Lugares' : 'Places', exact: true }).click()
  await page.getByRole('button', { name: helpGuideStrings[language].entry, exact: true }).click()
  await page.getByRole('radio', { name: es ? 'Inquietud sobre la calidad del agua' : 'Water-quality concern', exact: true }).click()
  const next = () => page.locator('.request-card-action .primary').click()
  await next()
  await expect(page.locator('.request-report-selection')).toHaveCount(0)
  await page.getByText(es ? 'Partículas en el agua' : 'Particles in the water', { exact: true }).click()
  await capture('selection')
  await next()
  await page.getByRole('button', { name: es ? '¿No la encuentras? Escríbela manualmente' : 'Can’t find it? Enter it manually' }).click()
  await page.getByLabel(es ? 'Dirección donde pasó (obligatorio)' : 'Address where this happened (required)').fill('100 Example Street')
  await next()
  await expect(page.getByRole('checkbox', { name: /Verify this reading|Verificar esta lectura/ })).toHaveCount(0)
  await expect(page.getByRole('checkbox', { name: es ? 'Investigar la inquietud reportada' : 'Investigate the reported concern', exact: true })).toBeChecked()
  await next()
  await expect(page.locator('.request-screen-response')).toBeVisible()
  await expect(page.locator('.request-card-action .primary')).toBeInViewport({ ratio: 1 })
  await capture('contact-details')
  await next()
  await page.getByRole('button', { name: es ? 'Revisar mi mensaje' : 'Review my message' }).click()
  const message = page.getByRole('textbox', { name: es ? 'Mensaje' : 'Message', exact: true })
  await expect(message).toHaveValue(new RegExp(title))
  await expect(message).toHaveValue(/2025/)
  await expect(message).toHaveValue(/#page=2/)
  await expect(message).toHaveValue(es ? /medidas correctivas/ : /corrective steps/)
  await expect(message).toHaveValue(es ? /documentos de respaldo/ : /supporting records/)
   await expect(message).toHaveValue(es ? /residentes deben tomar/ : /residents need to take action/)
   await expect(message).toHaveValue(es ? /Fuentes\n\[1\]/ : /Sources\n\[1\]/)
   expect((await message.inputValue()).split('\n').filter(line => line.startsWith('- '))).toHaveLength(1)
  await expect(page.getByText('Contact and next steps', { exact: true })).toHaveCount(0)
  await expect(page.locator('.request-progress-heading').getByRole('button', { name: es ? 'Revisar respuestas' : 'Review answers', exact: true })).toBeVisible()
  await capture('review')
  await expect(page.getByRole('region', { name: es ? 'Resumen de las respuestas del formulario' : 'Summary of form answers' })).toHaveCount(0)
  await expect(page.locator('.request-email-toolbar')).toBeInViewport({ ratio: 1 })
  await expect(page.locator('.request-card-action')).toBeInViewport({ ratio: 1 })
  if (page.viewportSize()!.width < 761) {
    const footer = await page.locator('.request-card-action').boundingBox()
    const navigation = await page.getByRole('navigation').boundingBox()
    expect(footer!.y + footer!.height).toBeLessThanOrEqual(navigation!.y)
  }
  await page.getByRole('button', { name: es ? 'Abrir Historial' : 'Open History', exact: true }).click()
  await page.getByRole('button', { name: es ? 'Continuar borrador' : 'Continue draft', exact: true }).click()
  await expect(message).toHaveValue(new RegExp(title))
  await page.getByRole('button', { name: es ? 'Revisar respuestas' : 'Review answers', exact: true }).click()
  await expect(page.getByRole('button', { name: es ? 'Editar selección del informe' : 'Edit report selection' })).toHaveCount(0)
  await expect(page.getByRole('region', { name: es ? 'Resumen de las respuestas del formulario' : 'Summary of form answers' })).toContainText(title)
  await capture('answers')
  await page.getByRole('button', { name: es ? 'Volver al correo' : 'Back to email', exact: true }).click()
  await message.fill('My manual email edits remain intact.')
  await page.getByRole('button', { name: es ? 'Revisar respuestas' : 'Review answers', exact: true }).click()
  await page.getByRole('button', { name: es ? 'Volver al correo' : 'Back to email', exact: true }).click()
  await expect(message).toHaveValue('My manual email edits remain intact.')
  if (page.viewportSize()!.width < 761) {
    await expect(page.locator('.review-next')).not.toHaveAttribute('open', '')
    await page.locator('.review-next > summary').click()
    await expect(page.locator('.review-next li')).toHaveCount(3)
    await expect(page.locator('.review-next li').last()).toBeVisible()
  }
  expect(errors).toEqual([])
})
