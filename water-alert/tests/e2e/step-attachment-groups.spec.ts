import { test, expect } from '@playwright/test'

test.use({ reducedMotion: 'reduce' })
for (const language of ['en', 'es'] as const) test(`attachments belong to their step (${language})`, async ({ page, context, baseURL }) => {
  const es = language === 'es'
  await context.addInitScript(language => {
    sessionStorage.setItem('wave:logo-intro:v1', 'seen')
    localStorage.setItem('water-alert:mode', 'sample')
    localStorage.setItem('water-alert:sample:v1', JSON.stringify({ watches: ['ADH:sample-creek'], liftWatches: [], language, checkOnOpen: false }))
  }, language)
  await context.route('**/*', route => {
    const u = new URL(route.request().url())
    if (u.origin !== baseURL) return route.abort()
    if (u.pathname === '/api/push/config') return route.fulfill({ json: { enabled: false } })
    if (u.pathname === '/api/status') return route.fulfill({ json: { places: [], sources: [], archive: [], coverageStart: null } })
    if (u.pathname.startsWith('/api/')) return route.abort()
    return route.continue()
  })
  const next = () => page.getByRole('button', { name: es ? 'Continuar' : 'Continue', exact: true }).click()
  const upload = (prefix: string) => Array.from({ length: 3 }, (_, i) => ({ name: `${prefix}-${i}.png`, mimeType: 'image/png', buffer: Buffer.from('test') }))
  await page.goto('/')
  await page.getByRole('button', { name: es ? 'Lugares' : 'Places', exact: true }).click()
  await page.getByRole('button', { name: es ? 'Obtener ayuda con un problema de agua' : 'Get help with a water issue', exact: true }).first().click()
  await page.getByRole('radio', { name: es ? /Interrupción del servicio/ : /Service/ }).click()
  await next()
  await page.getByRole('textbox', { name: es ? '¿Algo más? (opcional)' : 'Anything else? (optional)', exact: true }).fill('Synthetic issue')
  await page.locator('.request-action-media input[type=file]').setInputFiles(upload('first'))
  await expect(page.locator('.request-attachment-row')).toHaveCount(3)
  await expect(page.locator('.request-attachment-row').first().locator('button svg')).toHaveCount(1)
  await page.locator('.request-action-media input[type=file]').setInputFiles(upload('extra').slice(0, 1))
  await expect(page.getByRole('alert')).toContainText(es ? 'por paso' : 'per step')
  await next()
  await page.getByRole('button', { name: es ? '¿No la encuentras? Escríbela manualmente' : 'Can’t find it? Enter it manually', exact: true }).click()
  await page.getByLabel(es ? 'Dirección donde pasó (obligatorio)' : 'Address where this happened (required)', { exact: true }).fill('100 Synthetic Street')
  await next()
  await expect(page.locator('.request-attachment-row')).toHaveCount(0)
  await page.locator('.request-action-media input[type=file]').setInputFiles(upload('second'))
  await expect(page.locator('.request-attachment-row')).toHaveCount(3)
  await next()
  await expect(page.locator('.request-attachment-row')).toHaveCount(0)
  await page.locator('.request-extras input[type=file]').setInputFiles(upload('third'))
  await expect(page.locator('.request-attachment-row')).toHaveCount(3)
  await page.getByRole('button', { name: `${es ? 'Eliminar archivo' : 'Remove attachment'}: third-0.png` }).click()
  await next()
  await page.getByRole('button', { name: es ? 'Revisar mi mensaje' : 'Review my message', exact: true }).click()
  await expect(page.locator('.review-file')).toHaveCount(8)
  await expect(page.locator('.review-file').filter({ hasText: 'first-0.png' })).toBeVisible()
  await expect(page.locator('.review-file').filter({ hasText: 'second-0.png' })).toBeVisible()
  await expect(page.locator('.review-file').filter({ hasText: 'third-1.png' })).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
})
