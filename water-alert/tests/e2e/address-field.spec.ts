const feature = (housenumber: string, street: string, lon = -92.27, lat = 34.74) => ({ type: 'Feature', geometry: { type: 'Point', coordinates: [lon, lat] }, properties: { countrycode: 'US', state: 'Arkansas', city: 'Little Rock', postcode: '72201', housenumber, street, osm_type: 'N', osm_id: Number(housenumber) } })
const FEATURES = { type: 'FeatureCollection', features: [feature('100', 'Rock Street'), feature('100', 'Main Street'), feature('1', 'Out of State Rd', -90, 38)] }

/** Synthetic place, mocked help API and mocked Photon; nothing real is contacted or sent. */
async function openAddressStep(page: Page, context: import('@playwright/test').BrowserContext, baseURL: string | undefined, photon: 'ok' | 'fail' = 'ok') {
  const h = helpGuideStrings.en
  let records: HelpRequest[] = []
  const at = new Date().toISOString()
  const place = { id: LEISURE_HILLS_ID, name: 'LEISURE HILLS MOBILE HOME PARK', county: 'Benton', kind: 'system' }
  await context.addInitScript(({ id }) => {
    sessionStorage.setItem('wave:logo-intro:v1', 'seen')
    localStorage.setItem('water-alert:live:v1', JSON.stringify({ watches: [id], liftWatches: [], language: 'en', checkOnOpen: true }))
  }, { id: place.id })
  await context.route('**/*', route => {
    const url = new URL(route.request().url())
    if (url.hostname === 'photon.komoot.io') return photon === 'ok' ? route.fulfill({ json: url.pathname.startsWith('/reverse') ? { type: 'FeatureCollection', features: [feature('7', 'Located Lane')] } : FEATURES }) : route.abort()
    if (url.origin === baseURL && url.pathname === '/api/push/config') return route.fulfill({ json: { enabled: false } })
    if (url.origin === baseURL && url.pathname === '/api/help/session') return route.fulfill({ json: { enabled: true, user: { id: 'synthetic-user', email: 'resident@example.test' }, delivery: false, accountUrl: '' } })
    if (url.origin === baseURL && url.pathname === '/api/help/requests') {
      if (route.request().method() === 'GET') return route.fulfill({ json: records })
      const { draft, revision } = route.request().postDataJSON(); const record: HelpRequest = { id: draft.id, draft, revision: revision + 1, owner: 'synthetic-user', status: 'open', updatedAt: Date.now(), messages: [], events: [], replyToken: 'synthetic' }
      records = [record]; return route.fulfill({ json: record })
    }
    if (url.origin === baseURL && url.pathname === '/api/status') return route.fulfill({ json: { places: [place], sources: (Object.keys(SOURCES) as string[]).map(agency => ({ agency, records: [], lastSuccessAt: at, retrievedAt: at, error: null })) } })
    if (url.origin !== baseURL || url.pathname.startsWith('/api/')) return route.abort()
    return route.continue()
  })
  await page.goto('/')
  await page.getByRole('button', { name: 'Places', exact: true }).click()
  await page.getByRole('button', { name: h.entry, exact: true }).click()
  await page.getByRole('radio', { name: 'Service interruption or low pressure', exact: true }).click()
  await page.getByRole('button', { name: 'Continue' }).click()
  await page.locator('.request-wording-choice label').first().click()
  await page.getByRole('button', { name: 'Continue' }).click()
  await expect(page.getByRole('heading', { name: 'Where and when' })).toBeVisible()
  return page.getByRole('combobox', { name: /Address where this happened/ })
}

test('address must be picked from the list, edit-after-select clears it, keyboard works', async ({ page, context, baseURL }) => {
  const address = await openAddressStep(page, context, baseURL)
  await expect(address).toHaveAttribute('aria-autocomplete', 'list')
  await expect(page.locator('label[for]', { hasText: 'Address where this happened (required)' })).toBeVisible()
  // Continue without an address is blocked with a clear message.
  await page.getByRole('button', { name: 'Continue' }).click()
  await expect(page.getByRole('alert').filter({ hasText: 'Choose an address from the list, or enter it manually' })).toBeVisible()
  await expect(page.getByRole('heading', { name: 'Where and when' })).toBeVisible()
  await expect(address).toHaveAttribute('aria-invalid', 'true')
  // Under 4 characters: no search.
  await address.fill('100')
  await expect(page.getByRole('listbox')).toHaveCount(0)
  // Keyboard-only: type, ArrowDown x2, Enter. Out-of-state results are filtered, max 5.
  await address.fill('100 Main')
  await expect(page.locator('.address-listbox').getByRole('option')).toHaveCount(3)
  await expect(address).toHaveAttribute('aria-expanded', 'true')
  await address.press('ArrowDown'); await address.press('ArrowDown')
  await expect(page.locator('.address-listbox').getByRole('option').nth(1)).toHaveAttribute('aria-selected', 'true')
  await expect(address).toHaveAttribute('aria-activedescendant', /-opt-1$/)
  await address.press('Enter')
  await expect(address).toHaveValue('100 Main Street, Little Rock, AR 72201')
  await expect(address).not.toHaveAttribute('aria-invalid', 'true')
  await expect(page.getByRole('listbox')).toHaveCount(0)
  // Editing after selecting clears the selection: blurring now shows the inline error.
  await address.press('End'); await address.press('x')
  await page.getByLabel('Account number (optional)').focus()
  await expect(page.getByRole('alert').filter({ hasText: /^Choose an address from the list, or enter it manually\.$/ })).toBeVisible()
  // Escape closes; Tab closes without selecting.
  await address.fill('100 Rock')
  await expect(page.locator('.address-listbox').getByRole('option')).toHaveCount(3)
  await address.press('Escape')
  await expect(page.getByRole('listbox')).toHaveCount(0)
  await address.fill('100 Rock S')
  await expect(page.locator('.address-listbox').getByRole('option')).toHaveCount(3)
  await address.press('Tab')
  await expect(page.getByRole('listbox')).toHaveCount(0)
  await expect(address).toHaveValue('100 Rock S')
  // Pick with the mouse, continue, go back: the stored selection is restored.
  await address.fill('100 Rock')
  await page.locator('.address-listbox').getByRole('option').first().click()
  await page.getByRole('button', { name: 'Continue' }).click()
  await expect(page.getByRole('heading', { name: 'What would you like them to do?' })).toBeVisible()
  await page.getByRole('button', { name: /Back/ }).click()
  await expect(page.locator('.address-field input')).toHaveValue('100 Rock Street, Little Rock, AR 72201')
})

