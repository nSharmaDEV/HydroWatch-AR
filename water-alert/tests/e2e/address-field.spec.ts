test('Use my location: permission denied is handled; allowed fills a selected address', async ({ page, context, baseURL }) => {
  await context.addInitScript(() => {
    const mode = () => (window as unknown as { __geo?: string }).__geo
    Object.defineProperty(navigator, 'geolocation', { configurable: true, value: { getCurrentPosition: (ok: PositionCallback, fail: PositionErrorCallback) => mode() === 'allow' ? ok({ coords: { latitude: 34.74, longitude: -92.27 } } as GeolocationPosition) : fail({ code: 1, message: 'denied' } as GeolocationPositionError) } })
  })
  await openAddressStep(page, context, baseURL)
  await page.getByRole('button', { name: 'Use my location' }).click()
  await expect(page.getByText('We couldn’t get your location. You can type your address instead.')).toBeVisible()
  await expect(page.locator('.address-field input')).toHaveValue('')
  await page.evaluate(() => { (window as unknown as { __geo?: string }).__geo = 'allow' })
  await page.getByRole('button', { name: 'Use my location' }).click()
  await expect(page.locator('.address-field input')).toHaveValue('7 Located Lane, Little Rock, AR 72201')
  await page.getByRole('button', { name: 'Continue' }).click()
  await expect(page.getByRole('heading', { name: 'What would you like them to do?' })).toBeVisible()
})

