import { test, expect } from '@playwright/test'
import { LEISURE_HILLS_ID } from '../../src/annual-reports'

test('reviewed report finding travels through the guided request without sending', async ({ page, context, baseURL }) => {
  test.setTimeout(60_000)
  const place = { id: LEISURE_HILLS_ID, name: 'LEISURE HILLS MOBILE HOME PARK', county: 'Benton', kind: 'system' }
  const at = new Date().toISOString()
  await context.addInitScript(id => {
    sessionStorage.setItem('wave:logo-intro:v1', 'seen')
    localStorage.setItem('water-alert:live:v1', JSON.stringify({ watches: [id], liftWatches: [], language: 'en', checkOnOpen: true }))
  }, place.id)
  await context.route('**/*', route => {
    const url = new URL(route.request().url())
    if (url.origin !== baseURL) return route.abort()
    if (url.pathname === '/api/status') return route.fulfill({ json: { places: [place], sources: ['ADH', 'ADEQ'].map(agency => ({ agency, records: [], lastSuccessAt: at, retrievedAt: at, error: null })), archive: [], coverageStart: at } })
    if (url.pathname === '/api/help/session') return route.fulfill({ json: { enabled: false, user: null, delivery: false, accountUrl: null } })
    if (url.pathname === '/api/push/config') return route.fulfill({ json: { enabled: false } })
    if (url.pathname.startsWith('/api/')) return route.abort()
    return route.continue()
  })
  await page.goto('/')
  await page.getByRole('button', { name: 'Places', exact: true }).click()
  await page.getByRole('button', { name: /Provider information/ }).click()
   await page.getByRole('button', { name: 'All recorded problems · 4', exact: true }).click()
   await page.getByRole('button', { name: 'Ask about this', exact: true }).first().click()
  const next = () => page.getByRole('button', { name: 'Continue', exact: true }).click()
  await next()
  await expect(page.locator('.request-report-selection')).toHaveCount(0)
  await next()
  await page.getByRole('button', { name: 'Can’t find it? Enter it manually' }).click()
  await page.getByLabel('Address where this happened (required)').fill('100 Example Street')
  await next()
  await next()
  await next()
  await page.getByRole('button', { name: 'Review my message' }).click()
   await expect(page.getByRole('textbox', { name: 'Message', exact: true })).toHaveValue(/These are historical findings/i)
   const message = await page.getByRole('textbox', { name: 'Message', exact: true }).inputValue()
   expect(message.split('\n').filter(line => line.startsWith('- '))).toHaveLength(4)
   expect(message).toContain('Which requirement was unmet')
   expect(message).toContain('What violation required the notice')
   expect(message.lastIndexOf('Sources\n')).toBeGreaterThan(message.indexOf('Thank you'))
  await page.getByRole('button', { name: 'Review answers', exact: true }).click()
  await expect(page.getByRole('region', { name: 'Summary of form answers' })).toContainText('included automatically')
})
