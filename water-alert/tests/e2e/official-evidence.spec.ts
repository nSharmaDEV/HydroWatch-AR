for (const language of ['en', 'es'] as const) test(`compact provider card without identified issues (${language})`, async ({ page, context, baseURL }, info) => {
  const es = language === 'es', place = { id: `ADH:${'a'.repeat(64)}`, name: 'Synthetic supplier', county: 'Benton', kind: 'system' }
  const at = new Date().toISOString()
  await context.addInitScript(({ place, language }) => {
    sessionStorage.setItem('wave:logo-intro:v1', 'seen')
    localStorage.setItem('water-alert:live:v1', JSON.stringify({ watches: [place.id], liftWatches: [], language, checkOnOpen: true }))
    localStorage.setItem('wave:report-check:v1', JSON.stringify({ [place.id]: { state: 'aiSummarized', year: 2025, url: 'https://health.arkansas.gov/eng/d.aspx?P=001&YEAR=2025', checkedAt: '2026-11-17', summarizedOn: '2026-11-17', model: 'synthetic', issues: [] } }))
  }, { place, language })
  await context.route('**/*', route => {
    const url = new URL(route.request().url())
    if (url.origin !== baseURL) return route.abort()
    if (url.pathname === '/api/status') return route.fulfill({ json: { places: [place], sources: ['ADH', 'ADEQ'].map(agency => ({ agency, records: [], lastSuccessAt: at, retrievedAt: at, error: null })), archive: [], coverageStart: at } })
    if (url.pathname === '/api/help/session') return route.fulfill({ json: { enabled: false, user: null, delivery: false, accountUrl: null } })
    if (url.pathname === '/api/push/config') return route.fulfill({ json: { enabled: false } })
    if (url.pathname.startsWith('/api/')) return route.abort()
    return route.continue()
  })
  await page.goto('/')
  await page.getByRole('button', { name: es ? 'Lugares' : 'Places', exact: true }).click()
  await page.getByRole('button', { name: /Provider information|Información del proveedor/ }).click()
  const card = page.locator('.provider-card.annual-report')
  await card.scrollIntoViewIfNeeded()
  await expect(card).toHaveCount(1)
   await expect(card.locator('.evidence-filters')).toHaveCount(0)
   // Records read with nothing identified: the neutral chip, never a hidden zero.
   await expect(page.locator('.provider-info-chip')).toContainText(es ? 'No se encontraron problemas' : 'No problems found')
   await expect(page.locator('.provider-info-chip')).toHaveClass(/status-pill-clear/)
   await expect(card.locator('.evidence-type-group')).toHaveCount(0)
  await expect(card.getByRole('heading', { name: es ? 'Informe anual' : 'Annual report' })).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  if (process.env.WAVE_HELP_CAPTURE_DIR) await page.screenshot({ path: `${process.env.WAVE_HELP_CAPTURE_DIR}/${info.project.name}-${language}-empty.png` })
  await expect(card.getByRole('button', { name: es ? 'Detalles de las fuentes' : 'Source details' })).toHaveCount(0)
  // Check now and the official source share the card's action row.
  const status = page.locator('.status-card').first()
  await expect(status.locator('.card-check-actions').getByRole('button', { name: es ? 'Consultar ahora' : 'Check now' })).toBeVisible()
  // Nothing draws a rule between the card actions and Provider information.
  const below = await status.locator('.card-check-actions').evaluate(row => {
    const bottom = row.getBoundingClientRect().bottom
    return Array.from(row.closest('.status-card')!.querySelectorAll('*')).filter(el => {
      const box = el.getBoundingClientRect(), style = getComputedStyle(el)
      return box.width > 50 && box.top >= bottom - 1 && box.top <= bottom + 30 && parseFloat(style.borderTopWidth) > 0 && style.borderTopStyle !== 'none' && !el.closest('.provider-info-chip')
    }).map(el => el.className)
  })
  expect(below).toEqual([])
})
