  const before = (await screen.findByLabelText<HTMLTextAreaElement>('Message')).value
  if (!generated) expect(before).toBe('Frozen resident edits')
  // Legacy 'confirm' drafts resume on Send it; nothing is sent until the resident presses Send message.
  expect(screen.getByRole('heading', { level: 1, name: 'Review and send' })).toBeVisible()
  expect(screen.getByText('Step 4 of 4 · Review and send')).toBeVisible()
  fireEvent.click(screen.getByText('Send through WAVE instead'))
  expect(screen.getByRole('button', { name: 'Send message' })).toHaveClass('secondary')
  expect(screen.getByRole('button', { name: 'Send message' })).toBeEnabled()
  expect(sends).toHaveLength(0)
  fireEvent.click(screen.getByRole('button', { name: 'Send message' }))
  expect(await screen.findByText(/Message accepted by the email processor/)).toBeVisible()
  expect(screen.getByRole('heading', { level: 1, name: 'Review and send' })).toBeVisible()
