  expect(sends).toHaveLength(1)
  view.rerender(<RequestWorkspace place={place} language="es" sample={false} onBack={() => {}} onHistory={onHistory} />)
  expect(await screen.findByRole('button', { name: 'Enviar mensaje' })).toBeDisabled()
  expect(sends).toHaveLength(1)
