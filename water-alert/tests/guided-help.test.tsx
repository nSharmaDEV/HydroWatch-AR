import { cleanup, fireEvent, render, screen, waitFor, within } from '@testing-library/react'
import { afterEach, expect, test, vi } from 'vitest'
import { RequestWorkspace } from '../src/RequestWorkspace'
import { samplePlaces } from '../src/sample'
afterEach(() => { cleanup(); localStorage.clear() })
const props = { place: samplePlaces[0], language: 'en' as const, sample: true, onBack() {}, onHistory() {} }
test('one task per screen, skips empty records and preserves edits on back and resume', async () => {
  const view = render(<RequestWorkspace {...props} />)
  expect(await screen.findByText('Step 1 of 4 · What’s wrong?')).toBeVisible()
  expect(screen.queryByLabelText('How is this affecting you?')).not.toBeInTheDocument()
  fireEvent.click(screen.getByRole('button', { name: 'Other issue' }))
  // "Other" has no observation choices; its description is the one free-text field on screen 1.
  expect(screen.queryAllByRole('checkbox')).toHaveLength(0)
  expect([...document.querySelectorAll('textarea')].filter(t => !t.closest('details:not([open])'))).toHaveLength(1)
  expect(screen.queryByLabelText('What would you like the provider to do? (optional)')).not.toBeInTheDocument()
  expect(screen.getByRole('button', { name: 'Continue' })).toBeDisabled()
  fireEvent.change(screen.getByLabelText('What happened?'), { target: { value: 'Pressure stopped Monday' } })
  fireEvent.click(screen.getByRole('button', { name: 'Continue' }))
  expect(await screen.findByText('Step 2 of 4 · When and where')).toBeVisible()
  fireEvent.click(screen.getByRole('button', { name: 'Continue' }))
  expect(await screen.findByText('Step 3 of 4 · What should they do?')).toBeVisible()
  fireEvent.click(screen.getByRole('button', { name: 'Write my email' }))
  expect(await screen.findByText('Step 4 of 4 · Send it')).toBeVisible()
  fireEvent.change(await screen.findByLabelText('Message'), { target: { value: 'My own edited message' } })
  fireEvent.click(screen.getByRole('button', { name: 'Back' }))
  expect(await screen.findByText('Step 3 of 4 · What should they do?')).toBeVisible()
  for (let i = 0; i < 2; i++) fireEvent.click(screen.getByRole('button', { name: 'Back' }))
  expect(await screen.findByLabelText('What happened?')).toHaveValue('Pressure stopped Monday')
  for (let i = 0; i < 2; i++) fireEvent.click(screen.getByRole('button', { name: 'Continue' }))
  fireEvent.click(screen.getByRole('button', { name: 'Write my email' }))
  expect(await screen.findByLabelText('Message')).toHaveValue('My own edited message')
  await waitFor(() => expect(screen.getByText('Saved on this device')).toBeVisible())
  view.unmount(); render(<RequestWorkspace {...props} />)
  expect(await screen.findByLabelText('Message')).toHaveValue('My own edited message')
  expect(await screen.findByText('Step 4 of 4 · Send it')).toBeVisible()
  expect(screen.getByRole('region', { name: 'How to send it' })).toBeVisible()
  expect(screen.getAllByText('Sample — sending disabled.').length).toBeGreaterThan(0)
  expect(screen.queryByRole('button', { name: 'Continue to send' })).not.toBeInTheDocument()
  expect(screen.getByRole('button', { name: 'Copy email' })).toHaveClass('secondary')
  expect(screen.queryByRole('button', { name: 'Send message' })).not.toBeInTheDocument()
  expect(document.querySelector('a[href^="tel:"], a[href^="mailto:"]')).toBeNull()
  fireEvent.click(screen.getByRole('button', { name: 'Copy email' }))
  expect(await screen.findByText('Copy unavailable. Select the preview text or download it.')).toBeVisible()
})
test('record facts remain separate with complete attribution in the citations popup', async () => {
  const p = props.place
  render(<RequestWorkspace {...props} currentAdvisory notices={[{ id: 'synthetic', placeId: p.id, name: p.name, county: p.county, agency: 'ADH', kind: 'boil', area: 'North', issued: '2026-10-20', lifted: null, reason: 'Pressure loss\nRepair', url: 'https://example.test/notice' }]} />)
  expect(await screen.findByText('Step 1 of 4 · What’s wrong?')).toBeVisible()
  fireEvent.change(await screen.findByLabelText('Anything else? (optional)'), { target: { value: 'Need an update' } })
  for (let i = 0; i < 2; i++) fireEvent.click(screen.getByRole('button', { name: 'Continue' }))
  fireEvent.click(screen.getByRole('button', { name: 'Write my email' }))
  fireEvent.click(screen.getByRole('button', { name: 'Records (2 of 2 included)' }))
  expect(within(screen.getByRole('dialog', { name: 'Records' })).getAllByText('October 20, 2026')).toHaveLength(2)
  fireEvent.click(screen.getByRole('button', { name: 'Close records' }))
  expect(screen.queryByText('View source details')).not.toBeInTheDocument()
  fireEvent.click(screen.getByRole('button', { name: 'Cited sources' }))
  expect(screen.getByRole('dialog', { name: 'Cited sources' })).toBeVisible()
  fireEvent.click(screen.getByRole('button', { name: 'Close citations' }))
  vi.spyOn(window, 'confirm').mockReturnValue(true)
  fireEvent.click(screen.getByRole('button', { name: 'Update draft from answers' }))
  expect(screen.getByLabelText<HTMLTextAreaElement>('Message').value).toContain('Pressure loss')
  expect(screen.getByLabelText<HTMLTextAreaElement>('Message').value).toContain('Repair')
  fireEvent.click(screen.getByRole('button', { name: 'Records (2 of 2 included)' }))
  expect(within(screen.getByRole('dialog', { name: 'Records' })).getAllByRole('link', { name: /ADH/ })[0]).toHaveAttribute('href', 'https://example.test/notice')
})
