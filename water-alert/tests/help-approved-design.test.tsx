import { cleanup, fireEvent, render, screen, within } from '@testing-library/react'
import { afterEach, expect, test } from 'vitest'
import { RequestWorkspace } from '../src/RequestWorkspace'
import { samplePlaces } from '../src/sample'

afterEach(() => { cleanup(); localStorage.clear() })
test('first screen omits repeated supplier and issue instructions', async () => {
  render(<RequestWorkspace place={samplePlaces[0]} sample language="en" onBack={() => {}} onHistory={() => {}} />)
  await screen.findByRole('heading', { name: 'What’s wrong?', level: 1 })
  expect(screen.queryByText(samplePlaces[0].name)).not.toBeInTheDocument()
  expect(screen.queryByText('Choose the issue')).not.toBeInTheDocument()
  expect(screen.queryByText('Start with the closest match. You can change it before sending.')).not.toBeInTheDocument()
  expect(screen.queryByText(/Prefer to call/)).not.toBeInTheDocument()
})
test('back, saved/history controls and step navigation all belong inside the card', async () => {
  const { container } = render(<RequestWorkspace place={samplePlaces[0]} sample language="en" onBack={() => {}} onHistory={() => {}} />)
  const history = await screen.findByRole('button', { name: 'Open History' })
  const card = container.querySelector('.request-card')!
  expect(card).toContainElement(history)
  expect(card).toContainElement(screen.getByRole('button', { name: 'Back' }))
  expect(card.querySelector('.request-card-toolbar')).toBe(card.firstElementChild)
  expect(container.querySelector('.request-frame-topline .request-topline')).toBeNull()
  expect(card).toContainElement(screen.getByRole('navigation', { name: 'Request progress' }))
  expect(card.querySelector('.request-card-toolbar')).toContainElement(screen.getByRole('navigation', { name: 'Request progress' }))
})
test('approved four screens keep actions with context and personal details separate', async () => {
  render(<RequestWorkspace place={samplePlaces[0]} sample language="en" onBack={() => {}} onHistory={() => {}} />)
  fireEvent.click(await screen.findByRole('button', { name: 'Bill or charge' }))
  const issues = within(screen.getByRole('group', { name: 'Issue type' })).getAllByRole('button')
  expect(issues.at(-1)).toHaveTextContent('Other issue')
  fireEvent.click(screen.getByRole('checkbox', { name: 'A charge appears more than once' }))
  fireEvent.click(screen.getByRole('button', { name: 'Continue' }))
  expect(screen.getByRole('heading', { level: 1, name: 'When, Where, + Action' })).toBeVisible()
  expect(screen.getByRole('checkbox', { name: 'Review the charge' })).toBeChecked()
  fireEvent.change(screen.getByLabelText('Additional action details (optional)'), { target: { value: 'Explain the duplicate November charge.' } })
  expect(screen.queryByLabelText('Your name (optional)')).not.toBeInTheDocument()
  fireEvent.click(screen.getByRole('button', { name: 'Continue' }))
  expect(screen.getByRole('heading', { level: 1, name: 'Your details' })).toBeVisible()
  expect(screen.getByLabelText('What have you already tried? (optional)').tagName).toBe('TEXTAREA')
  fireEvent.change(screen.getByLabelText('Anything else to ask? (optional)'), { target: { value: 'Please reply in writing.' } })
  fireEvent.click(screen.getByRole('button', { name: 'Write my email' }))
  expect(screen.getByRole('heading', { level: 1, name: 'Review and send' })).toBeVisible()
  expect(screen.getByLabelText('Subject').tagName).toBe('TEXTAREA')
  expect(screen.getByLabelText<HTMLTextAreaElement>('Message').value).toContain('Explain the duplicate November charge')
  expect(screen.getByLabelText<HTMLTextAreaElement>('Message').value).toContain('Please reply in writing')
  expect(screen.getAllByRole('button', { name: 'Copy email' })).toHaveLength(1)
  fireEvent.click(screen.getByRole('button', { name: /1.*What’s wrong/ }))
  expect(screen.getByRole('heading', { level: 1, name: 'What’s wrong?' })).toBeVisible()
  fireEvent.click(screen.getByRole('button', { name: /2.*When, Where, \+ Action/ }))
  expect(screen.getByLabelText('Additional action details (optional)')).toHaveValue('Explain the duplicate November charge.')
})
test('later screens omit repeated supplier and introductory blocks', async () => {
  const { container } = render(<RequestWorkspace place={samplePlaces[0]} sample language="en" onBack={() => {}} onHistory={() => {}} />)
  fireEvent.change(await screen.findByLabelText('Anything else? (optional)'), { target: { value: 'Synthetic pressure concern' } })
  fireEvent.click(screen.getByRole('button', { name: 'Continue' }))
  expect(container.querySelector('.request-provider')).toBeNull()
  expect(screen.queryByRole('heading', { name: 'When and where' })).not.toBeInTheDocument()
  expect(screen.queryByText('Add what you know. These details help the recipient find the right record.')).not.toBeInTheDocument()
  fireEvent.click(screen.getByRole('button', { name: 'Continue' }))
  expect(container.querySelector('.request-provider')).toBeNull()
  expect(screen.queryByText('How can they reply?')).not.toBeInTheDocument()
  expect(screen.queryByText('Name, contact details and supporting documents are optional.')).not.toBeInTheDocument()
  fireEvent.click(screen.getByRole('button', { name: 'Write my email' }))
  expect(container.querySelector('.request-provider')).toBeNull()
  expect(screen.queryByRole('heading', { name: 'Your email' })).not.toBeInTheDocument()
  expect(screen.queryByRole('button', { name: 'Edit answers' })).not.toBeInTheDocument()
  expect(screen.queryByText('Read through and edit anything below before you send.')).not.toBeInTheDocument()
  expect(screen.getByLabelText('Message')).toBeVisible()
  expect(screen.getByRole('button', { name: 'Cited sources' })).toBeVisible()
})
test('cleared action defaults stay cleared after revisiting the first screen', async () => {
  render(<RequestWorkspace place={samplePlaces[0]} sample language="en" onBack={() => {}} onHistory={() => {}} />)
  fireEvent.change(await screen.findByLabelText('Anything else? (optional)'), { target: { value: 'Synthetic pressure issue' } })
  fireEvent.click(screen.getByRole('button', { name: 'Continue' }))
  fireEvent.click(screen.getByRole('checkbox', { name: 'Restore service' }))
  fireEvent.click(screen.getByRole('checkbox', { name: 'Share an update' }))
  fireEvent.click(screen.getByRole('button', { name: /1.*What’s wrong/ }))
  fireEvent.click(screen.getByRole('button', { name: 'Continue' }))
  expect(screen.getByRole('checkbox', { name: 'Restore service' })).not.toBeChecked()
  expect(screen.getByRole('checkbox', { name: 'Share an update' })).not.toBeChecked()
})
